#!/usr/bin/env bash
# Builds the audit eval fixture from a real PostgreSQL 17:
#   bash benchmarks/audit-fixture/build.sh
# 1. creates the shop database with planted problems (setup.sql),
# 2. runs traffic (workload.sql) and leaves one session idle in a transaction,
# 3. exports the standard statistics views (export.sql) to out/,
# 4. writes evals/audit-pg/scaffold.sh, which recreates those files in each
#    eval run's workspace.
set -euo pipefail
cd "$(dirname "$0")"
here=$(pwd)
out=$here/out
rm -rf "$out" && mkdir -p "$out"
c=dbskills-audit-fixture

docker rm -f "$c" >/dev/null 2>&1 || true
MSYS_NO_PATHCONV=1 docker run -d --name "$c" -e POSTGRES_PASSWORD=x \
  -v "$(cygpath -m "$out" 2>/dev/null || echo "$out"):/export" \
  postgres:17 -c shared_preload_libraries=pg_stat_statements -c pg_stat_statements.track=all -c work_mem=256MB -c max_connections=100 >/dev/null
for _ in $(seq 1 60); do docker exec "$c" psql -U postgres -h 127.0.0.1 -c 'select 1' >/dev/null 2>&1 && break; sleep 1; done

docker exec -i "$c" psql -q -v ON_ERROR_STOP=1 -U postgres -c "CREATE DATABASE shop"
docker exec -i "$c" psql -q -v ON_ERROR_STOP=1 -U postgres -d shop -c "CREATE EXTENSION pg_stat_statements"
docker exec -i "$c" psql -q -v ON_ERROR_STOP=1 -U postgres -d shop <setup.sql
docker exec -i "$c" psql -q -v ON_ERROR_STOP=1 -U postgres -d shop -c "SELECT pg_stat_statements_reset()" >/dev/null
docker exec -i "$c" psql -q -v ON_ERROR_STOP=1 -U postgres -d shop <workload.sql

# A worker that opened a transaction and never finished it.
( printf "SET application_name = 'billing-worker';\nBEGIN;\nUPDATE orders SET note = 'billing' WHERE id = 42;\n"; sleep 150 ) |
  docker exec -i "$c" psql -q -U postgres -d shop >/dev/null 2>&1 &
idle=$!
sleep 90

docker exec -i "$c" psql -q -U postgres -d shop -c "SELECT pg_stat_force_next_flush()" >/dev/null
docker exec -i "$c" psql -q -v ON_ERROR_STOP=1 -U postgres -d shop <export.sql
docker exec "$c" pg_dump -s -U postgres --no-owner --no-privileges shop | grep -v -e "^--" -e "^SET " -e "^SELECT pg_catalog" -e "^$" >"$out/schema.sql"
docker exec "$c" sh -c 'chmod a+r /export/*'

kill "$idle" 2>/dev/null || true
docker rm -f "$c" >/dev/null

cat >"$out/deploy.yaml" <<'EOF'
# orders-api deployment (excerpt)
service: orders-api
runtime: python 3.13, uvicorn
replicas: 12
uvicorn_workers_per_replica: 2
rolling_update: { max_surge: 25% }
database:
  host: shop-db.internal
  engine: postgres 17
  instance: 2 vCPU, 4 GiB RAM
  pool: { driver: asyncpg, min_size: 1, max_size: 4 }   # per worker
EOF

# Self-contained scaffold: one heredoc per exported file.
s=../../evals/audit-pg/scaffold.sh
mkdir -p "$(dirname "$s")"
{
  echo '#!/usr/bin/env bash'
  echo '# Generated by benchmarks/audit-fixture/build.sh. Recreates the DBA export.'
  echo 'set -euo pipefail'
  echo 'mkdir -p export'
  for f in "$out"/*; do
    name=$(basename "$f")
    echo "cat > export/$name <<'DBSKILLS_EOF'"
    cat "$f"
    echo 'DBSKILLS_EOF'
  done
} >"$s"
echo "wrote $s ($(wc -c <"$s") bytes) from: $(ls "$out" | tr '\n' ' ')"
